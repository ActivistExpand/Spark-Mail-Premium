def fibonacci(n):  
    a, b = 0, 1  
    for _ in range(n):  
        yield a  
        a, b = b, a + b  
for num in fibonacci(10):  
    print(num)  
sum_of_fibs = sum(fibonacci(10))  
print("Sum:", sum_of_fibs)
